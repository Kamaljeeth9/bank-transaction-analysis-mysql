limit 10;

#High-value transactions with high login attempts
select TransactionID, AccountID, TransactionAmount, LoginAttempts
from bank_transaction_clean
where TransactionAmount > (
select round(avg(TransactionAmount),2) as avg_transaction_amt
from bank_transaction_clean)
and LoginAttempts > (
select round(avg(LoginAttempts),2) as avg_login_attempt
from bank_transaction_clean)
order by TransactionAmount desc;

